-- A check works across PIN boundaries, but only if both PINs were validated by trusted sources.
-- Same PIN alone is never sufficient, and phone's CURRENT GPS never counts as home.
create function jansathi_internal.can_support_issue(p_report_id uuid) returns boolean
language plpgsql stable security definer set search_path=pg_catalog
as $$
declare
 v_home record;v_site record;v_report record;v_rules record;
begin
 if auth.uid() is null or not jansathi_internal.is_citizen_verified() then return false; end if;
 select r.user_id,r.status into v_report from public.jansathi_civic_reports r
 join public.jansathi_civic_feed f on f.id=r.id where r.id=p_report_id;
 if not found or v_report.user_id=auth.uid() or v_report.status in ('resolved','rejected') then return false; end if;
 select home_geog,area_kind,pincode into v_home
 from jansathi_internal.verified_residences h
 where h.user_id=auth.uid() and h.provenance='dbest_server_verified'
   and h.valid_until>now() and h.verified_at>now()-interval '90 days'
   and exists (
     select 1 from public.jansathi_member_entitlements e
     where e.user_id=h.user_id and e.dbest_member_id=h.dbest_member_id
       and e.source='dbest_server_sync' and e.source_verified_at>now()-interval '24 hours'
       and e.membership_status='active'
   );
 if not found then return false;end if;
 select issue_geog,pincode into v_site from jansathi_internal.verified_issue_sites where report_id=p_report_id;
 if not found then return false; end if;
 select urban_radius_m,rural_radius_m into v_rules from jansathi_internal.support_radius_settings where singleton;
 if not found then return false;end if;
 return extensions.st_dwithin(v_home.home_geog,v_site.issue_geog,
    case when v_home.area_kind='urban' then v_rules.urban_radius_m else v_rules.rural_radius_m end);
end $$;
revoke all on function jansathi_internal.can_support_issue(uuid) from public,anon,authenticated;
grant execute on function jansathi_internal.can_support_issue(uuid) to authenticated;

create function public.jansathi_can_support_issue(p_report_id uuid) returns boolean
language sql stable security invoker set search_path=pg_catalog
as $$select jansathi_internal.can_support_issue(p_report_id)$$;
revoke all on function public.jansathi_can_support_issue(uuid) from public,anon,authenticated;
grant execute on function public.jansathi_can_support_issue(uuid) to authenticated;

-- Override previous self-declared-village support logic (still retained as an optional view preference).
create or replace function jansathi_internal.validate_issue_support() returns trigger
language plpgsql security definer set search_path=pg_catalog
as $$
begin
 new.user_id:=auth.uid();
 if new.user_id is null or not jansathi_internal.can_support_issue(new.report_id) then
   raise exception 'Support requires a current verified DBest residential PIN/location within the configured radius of a verified issue' using errcode='42501';
 end if;
 new.created_at:=now();
 return new;
end $$;

-- Owner review needs source-of-truth issue and a responsible, documented verification.
create function jansathi_internal.approve_issue_geo(
 p_report_id uuid,p_pincode text,p_lat double precision,p_lon double precision,p_reason text
) returns boolean
language plpgsql security definer set search_path=pg_catalog
as $$
begin
 if not jansathi_internal.is_owner() then
   raise exception 'Verified Project Owner only' using errcode='42501';
 end if;
 if p_report_id is null or p_pincode !~ '^[1-9][0-9]{5}$' or
   p_lat not between 6 and 38 or p_lon not between 68 and 98 or
   length(btrim(coalesce(p_reason,''))) not between 10 and 500 then
   raise exception 'PIN, Indian-range location and a verification reason required' using errcode='22023';
 end if;
 if not exists(select 1 from public.jansathi_civic_feed f where f.id=p_report_id) then
    raise exception 'Issue must be publicly visible before support site verification' using errcode='22023';
 end if;
 insert into jansathi_internal.verified_issue_sites(report_id,pincode,issue_geog,verified_by,verification_reason)
 values(p_report_id,p_pincode,extensions.st_setsrid(extensions.st_makepoint(p_lon,p_lat),4326)::extensions.geography,
        auth.uid(),btrim(p_reason))
 on conflict(report_id) do update set
    pincode=excluded.pincode,issue_geog=excluded.issue_geog,verified_by=excluded.verified_by,
    verification_reason=excluded.verification_reason,verified_at=now();
 return true;
end $$;
revoke all on function jansathi_internal.approve_issue_geo(uuid,text,double precision,double precision,text) from public,anon,authenticated;
grant execute on function jansathi_internal.approve_issue_geo(uuid,text,double precision,double precision,text) to authenticated;
create function public.jansathi_owner_approve_issue_geo(
 p_report_id uuid,p_pincode text,p_lat double precision,p_lon double precision,p_reason text
) returns boolean
language sql volatile security invoker set search_path=pg_catalog
as $$select jansathi_internal.approve_issue_geo(p_report_id,p_pincode,p_lat,p_lon,p_reason)$$;
revoke all on function public.jansathi_owner_approve_issue_geo(uuid,text,double precision,double precision,text) from public,anon,authenticated;
grant execute on function public.jansathi_owner_approve_issue_geo(uuid,text,double precision,double precision,text) to authenticated;

create function jansathi_internal.set_support_radii(p_urban_km integer,p_rural_km integer,p_reason text)
returns boolean language plpgsql security definer set search_path=pg_catalog
as $$
begin
 if not jansathi_internal.is_owner() then raise exception 'Owner only' using errcode='42501';end if;
 if p_urban_km not between 1 and 15 or p_rural_km not between 1 and 30 or
 length(btrim(coalesce(p_reason,''))) not between 5 and 500 then
    raise exception 'Radius or audit reason out of bounds' using errcode='22023';
 end if;
 update jansathi_internal.support_radius_settings
 set urban_radius_m=1000*p_urban_km,rural_radius_m=1000*p_rural_km,
     edited_by=auth.uid(),edited_at=now() where singleton;
 insert into jansathi_internal.support_radius_audit
  (urban_radius_m,rural_radius_m,reason,changed_by)
 values(1000*p_urban_km,1000*p_rural_km,btrim(p_reason),auth.uid());
 return true;
end $$;
revoke all on function jansathi_internal.set_support_radii(integer,integer,text) from public,anon,authenticated;
grant execute on function jansathi_internal.set_support_radii(integer,integer,text) to authenticated;
create function public.jansathi_owner_set_support_radii(p_urban_km integer,p_rural_km integer,p_reason text)
returns boolean language sql volatile security invoker set search_path=pg_catalog
as $$select jansathi_internal.set_support_radii(p_urban_km,p_rural_km,p_reason)$$;
