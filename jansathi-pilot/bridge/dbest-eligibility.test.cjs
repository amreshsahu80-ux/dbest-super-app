'use strict';
const assert=require('node:assert/strict');
const {entitlementFromDbest,tokenHash}=require('./dbest-eligibility.cjs');
const normal={external_id:'DB123',category:'promoter',status:'Active',payment_status:'Approved',email_verified:true,email:'verify@example.com',deleted_at:null,payload:{kyc_status:'Approved'}};
const grant=x=>entitlementFromDbest({...normal,...x});
assert.equal(grant({}).can_publish_news,true);
assert.equal(grant({payload:{kyc_status:'Pending'}}).can_publish_news,false);
assert.equal(grant({payload:{kyc_status:'Aadhaar Submitted'}}).can_publish_news,false);
assert.equal(grant({payload:{}}).can_publish_news,false);
assert.equal(grant({payment_status:'Pending Verification'}),null);
assert.equal(grant({status:'Payment Verification Pending'}),null);
assert.equal(grant({email_verified:false}),null);
assert.equal(grant({deleted_at:'2026-10-25'}),null);
assert.equal(grant({category:'starter',payment_status:'Starter Free',payload:{kyc_status:'Not Required'}}).can_publish_news,false);
assert.equal(grant({category:'guest'}).can_publish_news,false);
assert.equal(grant({external_id:'DMLEADER01'}),null);
assert.equal(grant({payload:{kyc_status:'Approved',demo_chain:true}}),null);
assert.equal(grant({category:'prime',payment_status:'Razorpay Verified'}).can_publish_news,true);
assert.equal(tokenHash('a'.repeat(64)).length,64);
assert.equal(tokenHash('weak'),null);
assert.equal(tokenHash('a'.repeat(700)),null);
console.log('PASS 15 DBest entitlement/session-token eligibility tests');
