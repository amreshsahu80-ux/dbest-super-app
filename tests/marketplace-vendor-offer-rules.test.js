'use strict';
const assert=require('node:assert/strict');
const {updateOffer,customerOfferView}=require('../api/marketplace/vendor-offer-rules');
const offer={vendor_id:'v1',master_product_id:'p1',price_inclusive_gst:250,mrp:300,stock:5,active:true};
const a=updateOffer({actorVendorId:'v1',offer,patch:{price_inclusive_gst:240,stock:10}});
assert.equal(a.price_inclusive_gst,240);
assert.equal(a.stock,10);
assert.equal(offer.stock,5);
assert.throws(()=>updateOffer({actorVendorId:'v2',offer,patch:{stock:1}}),/vendor_offer_forbidden/);
assert.throws(()=>updateOffer({actorVendorId:'v1',offer,patch:{vendor_id:'v2'}}),/unsupported_offer_field/);
assert.throws(()=>updateOffer({actorVendorId:'v1',offer,patch:{price_inclusive_gst:350}}),/price_exceeds_mrp/);
assert.throws(()=>updateOffer({actorVendorId:'v1',offer,patch:{stock:-1}}),/invalid_stock/);
assert.throws(()=>updateOffer({actorVendorId:'v1',offer,patch:{active:'true'}}),/invalid_active/);
const master={id:'p1',name:'Aashirvaad Atta 5 kg',brand:'ITC',image_url:'https://example.com/common.jpg',status:'approved'};
const vendor={id:'v1',name:'Vendor One',active:true,owner_approval:'Approved',operational_hold:false};
assert.equal(customerOfferView({master,offer,vendor}).vendorName,'Vendor One');
assert.equal(customerOfferView({master,offer:{...offer,vendor_image_url:'https://example.com/vendor.jpg',vendor_image_review_status:'approved'},vendor}).imageUrl,'https://example.com/vendor.jpg');
assert.equal(customerOfferView({master,offer:{...offer,vendor_image_url:'https://example.com/vendor.jpg',vendor_image_review_status:'pending_review'},vendor}).imageUrl,master.image_url);
assert.equal(customerOfferView({master,offer:{...offer,stock:0},vendor}),null);
assert.equal(customerOfferView({master,offer,vendor:{...vendor,operational_hold:true}}),null);
console.log('Vendor offer rules: 13 assertions passed');
