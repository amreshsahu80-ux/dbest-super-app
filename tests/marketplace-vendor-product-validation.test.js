'use strict';
const assert=require('node:assert/strict');
const {normalizeProduct,validateBatch}=require('../api/marketplace/vendor-product-validation');
const item={category:'electronics',name:'Laptop 14 inch',brand:'Sample',selling_price_inr_gst_inclusive:'45000',stock_qty:'2',mrp_inr:'50000'};
const x=normalizeProduct(item);
assert.equal(x.status,'pending_owner_review');
assert.equal(x.active,false);
assert.equal(x.gstStatus,'unverified');
assert.equal(x.price,45000);
assert.equal(x.stock,2);
assert.throws(()=>normalizeProduct({...item,price:-1,selling_price_inr_gst_inclusive:undefined}),/invalid_selling_price/);
assert.throws(()=>normalizeProduct({...item,stock_qty:-2}),/invalid_stock/);
assert.throws(()=>normalizeProduct({...item,mrp_inr:'30000'}),/invalid_mrp/);
assert.throws(()=>normalizeProduct({...item,image_url:'javascript:alert(1)'}),/invalid_image_url/);
const result=validateBatch([item,{...item},{...item,name:'Laptop 15 inch'}]);
assert.equal(result[0].ok,true);
assert.equal(result[1].error,'duplicate_in_batch');
assert.equal(result[2].ok,true);
assert.equal(normalizeProduct({category:'medicine',name:'Saline Nasal Spray',selling_price_inr_gst_inclusive:90}).prescriptionRequired,'REVIEW');
console.log('Vendor product upload validation: 12 assertions passed');
