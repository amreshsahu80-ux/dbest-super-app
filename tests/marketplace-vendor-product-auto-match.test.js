'use strict';
const assert=require('node:assert/strict');
const {autoMatchDecision}=require('../api/marketplace/vendor-product-auto-match-policy');
const vendor={id:'v1',active:true,owner_approval:'Approved',operational_hold:false};
const product={category:'electronics',name:'USB-C Charger',brand:'DBest',barcode:'8901234567890',prescriptionRequired:'FALSE'};
const master={id:'master1',category:'electronics',name:'USB-C Charger',brand:'DBest',barcode_gtin:'8901234567890',status:'approved',image_rights_verified:true,gst_verified_at:'2026-11-21T00:00:00Z',specifications:{}};
const decide=(patch={})=>autoMatchDecision({vendor,product,masters:[master],...patch});
assert.deepEqual(decide(),{eligible:true,masterProductId:'master1'});
assert.equal(decide({vendor:{...vendor,operational_hold:true}}).reason,'vendor_not_eligible');
assert.equal(decide({vendor:{...vendor,active:false}}).eligible,false);
assert.equal(decide({vendor:{...vendor,owner_approval:'Pending'}}).eligible,false);
assert.equal(decide({product:{...product,category:'medicine'}}).reason,'compliance_review_required');
assert.equal(decide({product:{...product,barcode:''}}).reason,'barcode_required_for_automatch');
assert.equal(decide({masters:[]}).reason,'master_match_required');
assert.equal(decide({masters:[master,master]}).reason,'ambiguous_master_match');
assert.equal(decide({masters:[{...master,status:'draft'}]}).reason,'master_not_publishable');
assert.equal(decide({masters:[{...master,specifications:{test_only:true}}]}).reason,'master_not_publishable');
assert.equal(decide({masters:[{...master,gst_verified_at:null}]}).reason,'master_compliance_unverified');
assert.equal(decide({masters:[{...master,image_rights_verified:false}]}).reason,'master_compliance_unverified');
assert.equal(decide({product:{...product,name:'Other Charger'}}).reason,'product_identity_mismatch');
console.log('Vendor product conservative auto-match policy tests passed');
